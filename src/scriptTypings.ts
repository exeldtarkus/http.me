// isi httpme.d.ts + jsconfig.json untuk IntelliSense `httpme.` di script pre / post (tanpa vscode)

export const SCRIPT_TYPINGS = `// http.me script API (generated by "http.me: Add Script Typings")
interface HttpmeHeaders {
  get(name: string): string | undefined;
  has(name: string): boolean;
  set(name: string, value: unknown): void;
  remove(name: string): void;
  all(): { name: string; value: string }[];
}
interface HttpmeStore {
  get(name: string): string | undefined;
  set(name: string, value: unknown): void;
  unset(name: string): void;
  has(name: string): boolean;
}
interface HttpmeExpect {
  toBe(expected: unknown): void;
  toEqual(expected: unknown): void;
  toContain(item: unknown): void;
  toMatch(pattern: RegExp | string): void;
  toBeTruthy(): void;
  toBeFalsy(): void;
  toBeLessThan(n: number): void;
  toBeGreaterThan(n: number): void;
  toHaveProperty(name: string): void;
}
interface Httpme {
  /** request to send (pre-request scripts can change it) */
  request: { method: string; url: string; body: string | undefined; headers: HttpmeHeaders };
  /** response (post-response scripts only) */
  response: { status: number; time: number; body: string; headers: HttpmeHeaders; text(): string; json(): any };
  /** active Environment: set() stores a current value (not written to the Environment file) */
  environment: HttpmeStore;
  /** variables for this request only; {{name}} uses them first */
  vars: HttpmeStore;
  cookies: { get(name: string): string | undefined; all(): { name: string; value: string }[] };
  test(name: string, fn: () => void | Promise<void>): void;
  expect(value: unknown): HttpmeExpect & { not: HttpmeExpect };
  /** pre-request: do not send this request */
  skip(): void;
}
declare const httpme: Httpme;
declare const console: { log(...a: unknown[]): void; info(...a: unknown[]): void; warn(...a: unknown[]): void; error(...a: unknown[]): void; debug(...a: unknown[]): void };
declare function require(id: 'crypto' | 'buffer' | 'url' | 'querystring' | 'util' | \`./\${string}\` | \`../\${string}\`): any;
declare const module: { exports: any };
declare const crypto: any;
declare function setTimeout(fn: () => void, ms?: number): unknown;
declare function clearTimeout(id: unknown): void;
`;

/** jsconfig.json baru; undefined = sudah ada (tidak ditimpa) */
export const jsconfigText = (existing: string | undefined): string | undefined =>
  existing === undefined ? `${JSON.stringify({ compilerOptions: { lib: ['es2022'], checkJs: false }, exclude: ['node_modules'] }, null, 2)}\n` : undefined;
